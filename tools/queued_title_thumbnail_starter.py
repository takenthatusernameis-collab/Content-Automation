#!/usr/bin/env python3
"""Print title and thumbnail concept starters for a queued topic (no packet folder required).

Pulls working_title, one_line, and problem from docs/topic_queue.md for the given id.
Emits several mechanism-focused title options and thumbnail text/visual concepts.
Grounded in queue data only. Does not invent hype, numbers, clickbait, or full WORDS.
Does not write files. Does not scaffold. Does not call APIs.

Useful while STALL_OAUTH_IDLE persists: prepares packaging for Q2+ so that when the human
later scaffolds, titles.md and thumbnail.md start from grounded options instead of blank.
Reduces recurring setup labor for every subsequent video. Pairs with the other queued starters
and idea_brief.py --queue. After scaffold, run title_scan.py and thumbnail_scan.py.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT / "tools") not in sys.path:
    sys.path.insert(0, str(ROOT / "tools"))

from queue_lib import parse_queue  # type: ignore


def suggest_titles(title: str, one_line: str, problem: str) -> list[str]:
    """Mechanism-focused titles. No shouted words, no weak patterns, no numbers."""
    # Prefer the working title as primary; add variants that name the stall or the install.
    ol = one_line[:70].rstrip(".") or title
    pr = problem[:60].rstrip(".") or "the morning stall"
    return [
        title,
        f"Install the start cue so {pr} stops",
        f"{ol}",
        f"Put the cue on the work itself",
        f"One visible default ends {pr}",
    ]


def suggest_thumb_concepts(title: str, one_line: str, problem: str) -> list[str]:
    """Short thumbnail text and visual notes. Avoid long text and clickbait."""
    ol_short = one_line[:40].rstrip(".") or title[:40]
    return [
        f"Text: '{ol_short}'  |  Visual: single object or file with a clear start marker; rest of list faded or closed.",
        f"Text: 'Start cue on the work'  |  Visual: before (open list) vs after (one marked first action) split, no faces, no metrics.",
        f"Text: '{title[:35]}'  |  Visual: physical or digital cue placed directly on the task surface or file.",
        "Text: none or very short  |  Visual: close-up of the installed cue alone; clean background.",
    ]


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Print title and thumbnail concept starters for a queued topic id (Q2 etc.). No packet, no writes, no invented hype."
    )
    parser.add_argument("--id", required=True, help="Topic id from docs/topic_queue.md (e.g. Q2)")
    args = parser.parse_args()

    queue_path = ROOT / "docs" / "topic_queue.md"
    if not queue_path.is_file():
        print(f"Missing queue: {queue_path}", file=sys.stderr)
        return 1

    rows = parse_queue(queue_path.read_text(encoding="utf-8"))
    row = next((r for r in rows if r["id"].upper() == args.id.upper()), None)
    if not row:
        print(f"No row for id {args.id} in topic queue.", file=sys.stderr)
        return 1
    if row["status"] == "used":
        print(f"# Note: {args.id} is already marked used. Suggestions still valid for reference.\n")

    title = row["working_title"]
    one_line = row["one_line"]
    problem = row["problem"] or "unspecified problem from queue"

    titles = suggest_titles(title, one_line, problem)
    thumbs = suggest_thumb_concepts(title, one_line, problem)

    print(f"# Title and thumbnail starter for {args.id}: {title}")
    print("# (generated by queued_title_thumbnail_starter.py; no invented hype, numbers, or clickbait)")
    print("# Copy preferred options into titles.md and thumbnail.md after scaffolding.")
    print("# Keep titles specific and mechanism-focused. Prefer under ~60 characters.")
    print("# Thumbnail text should be short; visuals should show the cue or the stall without metrics or faces.")
    print("# After scaffold: python3 tools/title_scan.py videos/NNN-slug && python3 tools/thumbnail_scan.py videos/NNN-slug")
    print()
    print("## Overview")
    print(f"- Working title: {title}")
    print(f"- One-line / mechanism: {one_line}")
    print(f"- Problem / stall: {problem}")
    print()
    print("## Title options (pick one or adapt; no shouted words)")
    for i, t in enumerate(titles, 1):
        print(f"{i}. {t}")
    print()
    print("## Thumbnail concepts")
    for i, th in enumerate(thumbs, 1):
        print(f"{i}. {th}")
    print()
    print("## Notes")
    print("- Titles should name the mechanism or the concrete stall, not generic productivity advice.")
    print("- Thumbnail text must match or closely support the chosen title (avoid 'Matches title: No').")
    print("- Do not invent statistics, testimonials, or personal stories.")
    print("- Preferred human next remains OAuth (python3 tools/oauth_complete_guide.py). Do not scaffold Q2 while STALL_OAUTH_IDLE.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
